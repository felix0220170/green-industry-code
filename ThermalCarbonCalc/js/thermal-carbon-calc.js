function getEnthalpyByPT(pressure, temp) {
    const steamTable = steamTableData;
    const pressures = steamTable.pressures;
    const temperatures = steamTable.temperatures;

    let p1, p2;
    for (let i = 0; i < pressures.length - 1; i++) {
        if (pressure >= pressures[i] && pressure <= pressures[i + 1]) {
            p1 = pressures[i];
            p2 = pressures[i + 1];
            break;
        }
    }

    if (p1 === undefined) {
        p1 = p2 = pressure < pressures[0] ? pressures[0] : pressures[pressures.length - 1];
    }

    let t1, t2;
    for (let i = 0; i < temperatures.length - 1; i++) {
        if (temp >= temperatures[i] && temp <= temperatures[i + 1]) {
            t1 = temperatures[i];
            t2 = temperatures[i + 1];
            break;
        }
    }

    if (t1 === undefined) {
        t1 = t2 = temp < temperatures[0] ? temperatures[0] : temperatures[temperatures.length - 1];
    }

    const getPressureKey = (p) => {
        const keys = Object.keys(steamTable.data);
        if (steamTable.data[p.toString()] !== undefined) return p.toString();
        for (const key of keys) {
            if (Math.abs(parseFloat(key) - p) < 0.0001) return key;
        }
        return null;
    };

    const p1Key = getPressureKey(p1);
    const p2Key = getPressureKey(p2);

    if (p1Key === null || p2Key === null) return null;

    const h1 = steamTable.data[p1Key][t1.toString()];
    const h2 = steamTable.data[p1Key][t2.toString()];
    const h3 = steamTable.data[p2Key][t1.toString()];
    const h4 = steamTable.data[p2Key][t2.toString()];

    if (h1 === null || h2 === null || h3 === null || h4 === null) return null;
    if (p1 === p2 && t1 === t2) return h1;
    if (p1 === p2) return linearInterpolation(temp, t1, h1, t2, h2);
    if (t1 === t2) return linearInterpolation(pressure, p1, h1, p2, h3);

    const h12 = linearInterpolation(temp, t1, h1, t2, h2);
    const h34 = linearInterpolation(temp, t1, h3, t2, h4);
    return linearInterpolation(pressure, p1, h12, p2, h34);
}

