function renderSteamTableSummary() {
    const pressures = steamTableData.pressures;
    const temperatures = steamTableData.temperatures;

    document.getElementById('steamDataCount').textContent = pressures.length * temperatures.length;

    const pressureTags = document.getElementById('pressureTags');
    let pressureHtml = '';
    pressures.forEach(p => {
        pressureHtml += `<span>${p.toFixed(3)}</span>`;
    });
    pressureTags.innerHTML = pressureHtml;

    const temperatureTags = document.getElementById('temperatureTags');
    let tempHtml = '';
    temperatures.forEach(t => {
        tempHtml += `<span>${t}</span>`;
    });
    temperatureTags.innerHTML = tempHtml;

    const headerRow = document.getElementById('steamTableHeader');
    const body = document.getElementById('steamTableBody');
    
    const samplePressures = pressures.slice(0, 5);
    const sampleTemps = temperatures.slice(0, 5);

    let headerHtml = '<th>压力/温度</th>';
    sampleTemps.forEach(t => {
        headerHtml += `<th>${t}°C</th>`;
    });
    headerRow.innerHTML = headerHtml;

    let bodyHtml = '';
    samplePressures.forEach(p => {
        bodyHtml += `<tr><td>${p.toFixed(3)} MPa</td>`;
        sampleTemps.forEach(t => {
            const pKey = p.toFixed(3).toString();
            const tKey = t.toString();
            const h = steamTableData.data[pKey] && steamTableData.data[pKey][tKey];
            bodyHtml += `<td>${h !== undefined && h !== null ? h.toFixed(2) : '-'}</td>`;
        });
        bodyHtml += '</tr>';
    });
    body.innerHTML = bodyHtml;
}

function downloadSteamTable() {
    const blob = new Blob([JSON.stringify(steamTableData, null, 2)], { type: 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = 'steam_table_easyquery_style.json';
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
}

