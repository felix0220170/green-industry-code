function linearInterpolation(x, x1, y1, x2, y2) {
    if (x2 === x1) return y1;
    return y1 + (y2 - y1) * (x - x1) / (x2 - x1);
}

function getSaturatedWaterEnthalpy(temp) {
    const table = wenshangTableData;
    if (temp <= table[0].temperature) return table[0].h_liquid;
    if (temp >= table[table.length - 1].temperature) return table[table.length - 1].h_liquid;

    for (let i = 0; i < table.length - 1; i++) {
        if (temp >= table[i].temperature && temp <= table[i + 1].temperature) {
            return linearInterpolation(temp, table[i].temperature, table[i].h_liquid,
                                      table[i + 1].temperature, table[i + 1].h_liquid);
        }
    }
    return null;
}

