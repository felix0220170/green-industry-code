        details += `<p>h(${temp.toFixed(2)}) = ${h11.toFixed(2)} + (${h12.toFixed(2)} - ${h11.toFixed(2)}) × (${temp.toFixed(2)} - ${t1}) / (${t2} - ${t1}) = ${h1.toFixed(2)} kJ/kg</p>`;
        
